// winpath.go ports exactly the subset of Node's win32 path functions that
// paths.ts calls: normalize, resolve and join (lib/path.js, Node v22/v24 — the
// file has been byte-stable across those versions for these functions).
//
// It exists because the comparison helpers must run identically on every
// platform, and Go's filepath (Windows build) disagrees with Node on the inputs
// that matter here: drive-relative paths ("C:"), device roots (\\.\…, \\?\…)
// and forward slashes. The algorithms below are transliterations of the JS,
// comments cite the original lines, and windows_test.go pins them against a
// vector table generated by running the real Node implementation.
package paths

import "strings"

// isWinPathSeparator: `\` or `/` (JS isPathSeparator, win32 side).
func isWinPathSeparator(c byte) bool { return c == '\\' || c == '/' }

// isWindowsDeviceRoot: ASCII drive letter (JS isWindowsDeviceRoot).
func isWindowsDeviceRoot(c byte) bool { return (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') }

// normalizeString ports the shared segment normalizer (path.js ~line 92):
// collapses separator runs, resolves `.` and `..` segments (dropping them only
// when allowAboveRoot, i.e. relative inputs keep their leading `..`s), and
// emits one separator between segments. Transliterated branch for branch.
func normalizeString(path string, allowAboveRoot bool, separator byte) string {
	var res strings.Builder
	lastSegmentLength := 0
	lastSlash := -1
	dots := 0
	code := byte(0)
	for i := 0; i <= len(path); i++ {
		if i < len(path) {
			code = path[i]
		} else if isWinPathSeparator(code) {
			break
		} else {
			code = '/'
		}
		if isWinPathSeparator(code) {
			if lastSlash == i-1 || dots == 1 {
				// NOOP
			} else if dots == 2 {
				if res.Len() < 2 || lastSegmentLength != 2 ||
					res.String()[res.Len()-1] != '.' || res.String()[res.Len()-2] != '.' {
					if res.Len() > 2 {
						// Drop the last segment: res becomes everything before its separator.
						s := res.String()
						cut := len(s) - lastSegmentLength - 1
						if cut < 0 {
							cut = 0
						}
						s = s[:cut]
						res.Reset()
						res.WriteString(s)
						if idx := strings.LastIndexByte(s, separator); idx >= 0 {
							lastSegmentLength = len(s) - 1 - idx
						} else {
							lastSegmentLength = len(s)
						}
						lastSlash = i
						dots = 0
						continue
					} else if res.Len() != 0 {
						res.Reset()
						lastSegmentLength = 0
						lastSlash = i
						dots = 0
						continue
					}
				}
				if allowAboveRoot {
					if res.Len() > 0 {
						res.WriteByte(separator)
						res.WriteString("..")
					} else {
						res.WriteString("..")
					}
					lastSegmentLength = 2
				}
			} else {
				if res.Len() > 0 {
					res.WriteByte(separator)
					res.WriteString(path[lastSlash+1 : i])
				} else {
					res.WriteString(path[lastSlash+1 : i])
				}
				lastSegmentLength = i - lastSlash - 1
			}
			lastSlash = i
			dots = 0
		} else if code == '.' && dots != -1 {
			dots++
		} else {
			dots = -1
		}
	}
	return res.String()
}

// matchWin32Root parses the leading device/root of a Windows path, mirroring the
// "Try to match a root" block of win32.normalize (path.js ~line 350).
type win32Root struct {
	device     string
	rootEnd    int
	isAbsolute bool
}

func matchWin32Root(path string) (win32Root, bool) {
	length := len(path)
	if length == 0 {
		return win32Root{}, false
	}
	code := path[0]
	if length == 1 {
		if isWinPathSeparator(code) {
			return win32Root{rootEnd: 1, isAbsolute: true}, true
		}
		return win32Root{}, false
	}
	var device string
	rootEnd := 0
	isAbsolute := false
	if isWinPathSeparator(code) {
		isAbsolute = true
		if isWinPathSeparator(path[1]) {
			// Possible UNC root: \\server\share…
			j := 2
			last := j
			for j < length && !isWinPathSeparator(path[j]) {
				j++
			}
			if j < length && j != last {
				firstPart := path[last:j]
				last = j
				for j < length && isWinPathSeparator(path[j]) {
					j++
				}
				if j < length && j != last {
					last = j
					for j < length && !isWinPathSeparator(path[j]) {
						j++
					}
					if j == length || j != last {
						if firstPart == "." || firstPart == "?" {
							// Device root, e.g. \\.\PHYSICALDRIVE0. Node's reserved-name
							// special case (\\?\COM1) is not ported: the validation never
							// produces such names.
							device = `\\` + firstPart
							rootEnd = 4
						} else {
							device = `\\` + firstPart + `\` + path[last:j]
							rootEnd = j
						}
					}
				}
			}
		} else {
			rootEnd = 1
		}
	} else if isWindowsDeviceRoot(code) && path[1] == ':' {
		device = path[:2]
		rootEnd = 2
		if length > 2 && isWinPathSeparator(path[2]) {
			isAbsolute = true
			rootEnd = 3
		}
	}
	return win32Root{device: device, rootEnd: rootEnd, isAbsolute: isAbsolute}, true
}

// Win32Normalize ports path.win32.normalize (path.js ~line 350). The
// reserved-device-name and CVE-2024-36139 branches are omitted: they fire only
// for inputs like `\\.\COM1` or bare `nul`-style reserved names, which the data
// dir validation never produces; the vector table documents the omission.
func Win32Normalize(path string) string {
	if path == "" {
		return "."
	}
	if len(path) == 1 {
		if isWinPathSeparator(path[0]) {
			return `\`
		}
		return path
	}
	root, _ := matchWin32Root(path)
	device := root.device
	rootEnd := root.rootEnd
	isAbsolute := root.isAbsolute

	tail := ""
	if rootEnd < len(path) {
		tail = normalizeString(path[rootEnd:], !isAbsolute, '\\')
	}
	if tail == "" && !isAbsolute {
		tail = "."
	}
	if len(tail) > 0 && isWinPathSeparator(path[len(path)-1]) {
		tail += `\`
	}
	if device == "" {
		if isAbsolute {
			return `\` + tail
		}
		return tail
	}
	if isAbsolute {
		return device + `\` + tail
	}
	return device + tail
}

// Win32Resolve ports path.win32.resolve(path) (path.js ~line 185). resolve() with
// no absolute argument falls back to the process cwd; cwd is therefore a
// parameter so the table test can pin that behaviour without a process. The
// drive-specific cwd (`=C:` env) branch is not ported — it only fires for
// drive-relative arguments, which the data-dir inputs never are.
func Win32Resolve(path, cwd string) string {
	resolvedDevice := ""
	resolvedTail := ""
	resolvedAbsolute := false

	// resolve(...args) walks the arguments back-to-front and the LAST absolute
	// argument wins; with the extra trailing cwd pass folded in, the effective
	// argument list is [path, cwd] and the visit order is cwd first, then path.
	for _, arg := range [2]string{path, cwd} {
		if arg == "" {
			continue
		}
		root, _ := matchWin32Root(arg)
		device := root.device
		rootEnd := root.rootEnd
		isAbsolute := root.isAbsolute
		if len(device) > 0 {
			if len(resolvedDevice) > 0 {
				if !strings.EqualFold(device, resolvedDevice) {
					// Points at another device; not applicable.
					continue
				}
			} else {
				resolvedDevice = device
			}
		}
		if resolvedAbsolute {
			if len(resolvedDevice) > 0 {
				break
			}
		} else {
			resolvedTail = arg[rootEnd:] + `\` + resolvedTail
			resolvedAbsolute = isAbsolute
			if isAbsolute && len(resolvedDevice) > 0 {
				break
			}
		}
	}

	resolvedTail = normalizeString(resolvedTail, !resolvedAbsolute, '\\')
	if resolvedAbsolute {
		return resolvedDevice + `\` + resolvedTail
	}
	out := resolvedDevice + resolvedTail
	if out == "" {
		return "."
	}
	return out
}

// Win32Join ports path.win32.join(parts…): normalize(join(non-empty args, `\`)).
func Win32Join(parts ...string) string {
	nonEmpty := make([]string, 0, len(parts))
	for _, part := range parts {
		if part != "" {
			nonEmpty = append(nonEmpty, part)
		}
	}
	if len(nonEmpty) == 0 {
		return "."
	}
	return Win32Normalize(strings.Join(nonEmpty, `\`))
}
