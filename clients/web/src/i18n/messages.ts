export type MessageKey = keyof typeof zhCN;

export function formatMsg(locale: LocaleCode, key: MessageKey, vars?: Record<string, string | number>): string {
  const dict = locale === 'en-US' ? enUS : zhCN;
  let template = dict[key] ?? zhCN[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      template = template.replaceAll(`{${k}}`, String(v));
    }
  }
  return template;
}
